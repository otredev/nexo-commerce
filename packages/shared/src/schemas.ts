/* ---------------- Catalog (Phase 1) ---------------- */

export const namedSchema = z.object({ name: z.string().trim().min(1, "Requerido").max(80) });

const cents = z.number().int("Usa centavos enteros").min(0, "No puede ser negativo").max(100_000_000_00);
const qty = z.number().min(0, "No puede ser negativo").max(1_000_000_000);

export const variantInputSchema = z.object({
  id: z.string().max(40).optional(),
  /** Empty → generated by the server. */
  sku: z.string().trim().max(64).default("").transform((v) => v.toUpperCase()),
  barcode: z.string().trim().max(64).nullable().default(null).transform((v) => (v ? v : null)),
  /** Values in the same order as the product's option names: ["M", "Negro"]. */
  options: z.array(z.string().trim().min(1, "Requerido").max(40)).max(3).default([]),
  priceCents: cents,
  costCents: cents.default(0),
  minStock: qty.default(0),
  /** Only used when creating: loads this quantity in the default location as "initial inventory". */
  initialStock: qty.optional(),
  active: z.boolean().default(true),
});
export type VariantInput = z.infer<typeof variantInputSchema>;

export const productInputSchema = z
  .object({
    name: z.string().trim().min(1, "Requerido").max(160),
    description: z.string().trim().max(5000).nullable().default(null).transform((v) => (v ? v : null)),
    categoryId: z.string().max(40).nullable().default(null),
    brandId: z.string().max(40).nullable().default(null),
    /** null → the business's default tax. */
    taxRateId: z.string().max(40).nullable().default(null),
    unit: z.enum(UNIT_CODES).default("unit"),
    trackInventory: z.boolean().default(true),
    /** Option names, e.g. ["Talla", "Color"]. Empty → simple product with one variant. */
    optionNames: z.array(z.string().trim().min(1, "Requerido").max(30)).max(3).default([]),
    images: z.array(z.string().max(300)).max(8).default([]),
    variants: z.array(variantInputSchema).min(1, "Agrega al menos una variante").max(100, "Máximo 100 variantes"),
  })
  .superRefine((p, ctx) => {
    if (p.optionNames.length === 0 && p.variants.length !== 1) {
      ctx.addIssue({ code: "custom", path: ["variants"], message: "Un producto sin opciones tiene exactamente una variante" });
    }
    const names = new Set(p.optionNames.map((n) => n.toLowerCase()));
    if (names.size !== p.optionNames.length) ctx.addIssue({ code: "custom", path: ["optionNames"], message: "Las opciones no pueden repetirse" });
    const combos = new Set<string>();
    const skus = new Set<string>();
    const barcodes = new Set<string>();
    p.variants.forEach((v, i) => {
      if (v.options.length !== p.optionNames.length) {
        ctx.addIssue({ code: "custom", path: ["variants", i, "options"], message: "Completa todas las opciones" });
      }
      const key = v.options.map((o) => o.toLowerCase()).join("\u0000");
      if (combos.has(key)) ctx.addIssue({ code: "custom", path: ["variants", i, "options"], message: "Combinación repetida" });
      combos.add(key);
      if (v.sku) {
        if (skus.has(v.sku.toLowerCase())) ctx.addIssue({ code: "custom", path: ["variants", i, "sku"], message: "SKU repetido" });
        skus.add(v.sku.toLowerCase());
      }
      if (v.barcode) {
        if (barcodes.has(v.barcode)) ctx.addIssue({ code: "custom", path: ["variants", i, "barcode"], message: "Código repetido" });
        barcodes.add(v.barcode);
      }
    });
  });
export type ProductInput = z.input<typeof productInputSchema>;
export type ProductInputParsed = z.output<typeof productInputSchema>;

export const stockMovementSchema = z
  .object({
    variantId: z.string().min(1).max(40),
    locationId: z.string().min(1).max(40),
    /** in: add · out: remove · set: physical count, fixes the stock to this quantity. */
    type: z.enum(["in", "out", "set"]),
    quantity: qty,
    /** Entries only: cost per unit, updates the weighted average cost. */
    unitCostCents: cents.nullable().default(null),
    reason: z.enum(REASON_CODES),
    note: z.string().trim().max(300).nullable().default(null).transform((v) => (v ? v : null)),
  })
  .superRefine((m, ctx) => {
    if (m.type !== "set" && m.quantity <= 0) ctx.addIssue({ code: "custom", path: ["quantity"], message: "La cantidad debe ser mayor a 0" });
  });
export type StockMovementInput = z.input<typeof stockMovementSchema>;

